#!/usr/bin/env python3
"""Generate the irace parameter space from grammars/imrt_bao.xml with grammar2code.

  python scripts/grammar2code_irace.py [--out irace/parameters_g2c.txt] [--depth 1]

The grammar is the single source: grammar2code turns every derivation into an irace parameter with its conditions.
Two things the XML cannot say are added here as irace [forbidden] rules: in the simulated annealing branches the
initial temperature must be greater than the final one.

Environment: GRAMMAR2CODE = path to the grammar2code executable (default: `grammar2code` in the PATH).
See docs/GUIA_MODELOS_Y_TOKENS.md for how to build it.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = """# irace parameter space generated by scripts/grammar2code_irace.py from grammars/imrt_bao.xml (do not edit by hand).
# Parameters are indexes into the alternatives of each derivation; irace/target-runner-g2c translates a
# configuration back into an EMILI command line with grammar2code.
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(ROOT, "irace", "parameters_g2c.txt"))
    ap.add_argument("--grammar", default=os.path.join(ROOT, "grammars", "imrt_bao.xml"))
    ap.add_argument("--depth", type=int, default=1, help="recursion depth passed to grammar2code (the grammar has no recursion)")
    a = ap.parse_args()
    g2c = os.environ.get("GRAMMAR2CODE", "grammar2code")
    with tempfile.TemporaryDirectory(prefix="g2c_") as tmp:
        raw = os.path.join(tmp, "parameters.txt")
        try:
            p = subprocess.run([g2c, a.grammar, "--depth=%d" % a.depth, "--parameters=" + raw], capture_output=True, text=True)
        except FileNotFoundError:
            sys.exit("grammar2code not found: build it and set GRAMMAR2CODE=<path to the executable>")
        if p.returncode != 0 or not os.path.exists(raw):
            sys.exit("grammar2code failed:\n" + p.stdout[-500:] + p.stderr[-500:])
        lines = [l.rstrip("\n") for l in open(raw) if l.strip()]
    names = [l.split("\t")[0] for l in lines]
    forbidden = ["%s <= %s" % (n, n[:-len("t_start")] + "t_end") for n in names
                 if n.endswith("t_start") and n[:-len("t_start")] + "t_end" in names]
    with open(a.out, "w") as f:
        f.write(HEADER)
        f.write("\n".join(lines) + "\n")
        if forbidden:
            f.write("\n[forbidden]\n" + "\n".join(forbidden) + "\n")
    print("%d parameters, %d forbidden rules -> %s" % (len(lines), len(forbidden), os.path.relpath(a.out, ROOT)))


if __name__ == "__main__":
    main()
